local semver = require("nuget.semver")

describe("semver", function()
  it("orders by number, not by text", function()
    assert.equals(-1, semver.compare("2.10.0", "3.0.0"))
    assert.equals(1, semver.compare("13.0.1", "9.0.1"))
    assert.equals(0, semver.compare("1.0", "1.0.0"))
  end)

  it("knows the legacy fourth number", function()
    assert.equals(1, semver.compare("1.2.3.4", "1.2.3"))
    assert.equals(-1, semver.compare("1.2.3.4", "1.2.3.10"))
  end)

  it("puts a release after its prereleases", function()
    assert.equals(1, semver.compare("4.4.0", "4.4.0-dev-02443"))
    assert.equals(-1, semver.compare("4.4.1-dev-02443", "4.4.1"))
    assert.equals(1, semver.compare("4.4.1-dev-02443", "4.4.0"))
  end)

  it("orders prerelease identifiers as SemVer 2.0 does", function()
    assert.equals(-1, semver.compare("1.0.0-alpha", "1.0.0-alpha.1"))
    assert.equals(-1, semver.compare("1.0.0-alpha.1", "1.0.0-alpha.beta"))
    assert.equals(-1, semver.compare("1.0.0-beta.2", "1.0.0-beta.11"))
    assert.equals(-1, semver.compare("1.0.0-rc.1", "1.0.0"))
  end)

  it("ignores build metadata", function()
    assert.equals(0, semver.compare("1.0.0+abc", "1.0.0+def"))
  end)

  it("sorts unparseable versions first", function()
    assert.equals(-1, semver.compare("garbage", "1.0.0"))
  end)

  it("finds the highest version, with or without prereleases", function()
    local versions = { "4.3.1", "4.4.1-dev-1", "4.4.0", "3.0.0" }
    assert.equals("4.4.0", semver.max(versions))
    assert.equals("4.4.1-dev-1", semver.max(versions, true))
  end)

  it("sorts newest first", function()
    assert.same({ "13.0.4", "13.0.1", "12.0.1", "9.0.1" }, semver.sort_desc({ "12.0.1", "9.0.1", "13.0.4", "13.0.1" }))
  end)

  it("evaluates NuGet version ranges", function()
    assert.is_true(semver.in_range("12.0.1", "(, 13.0.1)"))
    assert.is_false(semver.in_range("13.0.1", "(, 13.0.1)"))
    assert.is_true(semver.in_range("13.0.1", "(, 13.0.1]"))
    assert.is_true(semver.in_range("1.0.0", "[1.0, 2.0)"))
    assert.is_false(semver.in_range("1.0.0", "(1.0, 2.0)"))
    assert.is_false(semver.in_range("2.0.0", "[1.0, 2.0)"))
    assert.is_true(semver.in_range("4.7.0", "[4.7.0]"))
    assert.is_false(semver.in_range("4.7.1", "[4.7.0]"))
    assert.is_true(semver.in_range("2.5.0", "2.0"))
    assert.is_false(semver.in_range("1.9.0", "2.0"))
    assert.is_true(semver.in_range("5.0.0", "[4.0.0, )"))
  end)

  it("uses the resolved version for ranges and floating versions", function()
    assert.equals("1.2.3", semver.effective("1.2.3", "1.2.3"))
    assert.equals("1.5.0", semver.effective("[1.0,2.0)", "1.5.0"))
    assert.equals("1.9.2", semver.effective("1.*", "1.9.2"))
    assert.equals("2.0.0-beta.1", semver.effective("2.0.0-beta.1", "2.0.0-beta.1"))
  end)
end)
